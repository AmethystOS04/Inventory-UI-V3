function applyReality(realityName) {
    const reality = realities[realityName];

    if (!reality) return;

    document.documentElement.style.setProperty("--reality-panel", reality.panel);
    document.documentElement.style.setProperty("--reality-info-panel", reality.infoPanel);
    document.documentElement.style.setProperty("--reality-border", reality.border);
    document.documentElement.style.setProperty("--reality-accent", reality.accent);
    document.documentElement.style.setProperty("--reality-accent-2", reality.accent2);
    document.documentElement.style.setProperty("--reality-text", reality.text);
    document.documentElement.style.setProperty("--reality-muted", reality.muted);
    document.documentElement.style.setProperty(
    "--reality-border-glow",
    reality.borderGlow
);
}

function setReality(realityName) {
    applyReality(realityName);
    localStorage.setItem("reality", realityName);
}
const savedReality = localStorage.getItem("reality") || "default";

applyReality(savedReality);
const realitySelect = document.getElementById("realitySelect");

if (realitySelect) {
    const currentReality =
        localStorage.getItem("reality") || "default";

    realitySelect.value = currentReality;

    realitySelect.addEventListener("change", () => {
        setReality(realitySelect.value);
    });
}